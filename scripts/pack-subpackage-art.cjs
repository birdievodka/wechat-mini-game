const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const sharp = require('sharp');

const root = path.resolve(__dirname, '..');
const scale = .55;
const bossSources = 'art/runtime-bosses/hd-atlases';
const optionalSources = 'art/runtime-subpackages/sources';
const optionalBundles = ['arsenal', 'talismans', 'meadow', 'orchard', 'enemies'];
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const pngs = dir => fs.readdirSync(path.join(root, dir)).filter(file => file.endsWith('.png')).sort();

async function encode(source, dest, imageScale) {
  const input = fs.readFileSync(path.join(root, source));
  const image = sharp(input);
  const dimensions = await image.metadata();
  const width = Math.round(dimensions.width * imageScale);
  const height = Math.round(dimensions.height * imageScale);
  if (imageScale !== 1) image.resize(width, height, {fit: 'fill'});
  const jpeg = dest.endsWith('.jpg');
  const encoded = jpeg
    ? await image.jpeg({quality: 92, chromaSubsampling: '4:4:4', mozjpeg: true}).toBuffer()
    : await image.png({palette: true, colours: 256, effort: 7, dither: 0}).toBuffer();
  const output = !jpeg && imageScale === 1 && input.length <= encoded.length ? input : encoded;
  const outputPath = path.join(root, dest);
  fs.mkdirSync(path.dirname(outputPath), {recursive: true});
  fs.writeFileSync(outputPath, output);
  return {source, dest, width, height, bytes: output.length, sourceSha256: hash(input), sha256: hash(output)};
}

async function main() {
  const files = [];
  for (const bundle of fs.readdirSync(path.join(root, bossSources)).sort()) {
    for (const file of pngs(bossSources + '/' + bundle)) {
      files.push(await encode(bossSources + '/' + bundle + '/' + file, 'assets/remote-content/' + bundle + '/' + file, scale));
    }
  }
  for (const bundle of optionalBundles) {
    for (const file of pngs(optionalSources + '/' + bundle)) {
      const output = bundle === 'meadow' && file === 'ground.png' ? 'ground.jpg' : file;
      files.push(await encode(optionalSources + '/' + bundle + '/' + file, 'assets/' + bundle + '/' + output, 1));
    }
  }
  fs.writeFileSync(path.join(root, 'art/runtime-subpackages/manifest.json'), JSON.stringify({bossScale:scale,files}, null, 2) + '\n');
  fs.writeFileSync(path.join(root, 'assets/scripts/boss-atlas-scale.ts'),
    '// Generated by scripts/pack-subpackage-art.cjs.\nexport const BOSS_ATLAS_SCALE = ' + scale + ';\n');
  console.log('分包压缩图：' + files.length + ' 张，' + (files.reduce((sum, file) => sum + file.bytes, 0) / 1048576).toFixed(2) + ' MiB');
}
main().catch(error => {console.error(error);process.exitCode=1;});
