// Rendered footprints in battlefield units. 750-unit fixed-height camera; target 1,350 raster rows (1.8 samples per unit).
const fs=require('node:fs'),crypto=require('node:crypto'),sharp=require('sharp');
const hd=require('../art/runtime-boss-hd/sources.json');
// E01 has 362 texels for a 78-unit frame. Above screen density further texels are supersampling.
const farmerDensity=362/78, targetDensity=Math.min(farmerDensity,1350/750);
const cellFor=units=>Math.ceil(units*targetDensity/32)*32;
const propUnits=[150,78,63,94,66,66,57,95,95,95,145,145];
function frameSize(name,i){
 if(name==='boss-props'&&i>=12)return [cellFor(360),cellFor(180)];
 const units=name==='boss-props'?propUnits[i]:name==='boss-beasts'?[125,125,185,210][Math.floor(i/6)]:name==='lvbu-actions'?282:244.4;
 const size=Math.max(name==='boss-props'?192:0,cellFor(units));return [size,size];
}
let current;
async function sample(a,w,h){
 if(current?.source!==a.source){
  const record=hd.files.find(r=>r.source===a.source);
  if(!record||crypto.createHash('sha256').update(fs.readFileSync(a.source)).digest('hex')!==record.sourceSha256)
   throw Error('Refresh the HD master for '+a.source+' with scripts/remaster-boss-sources.cjs');
  const input=fs.readFileSync(record.file);
  if(crypto.createHash('sha256').update(input).digest('hex')!==record.sha256)throw Error('Boss HD master changed: '+record.file);
  current={source:a.source,input};
 }
 const [x,y,sw,sh]=a.sourceRect;
 const rgb=await sharp(current.input).extract({left:x*2,top:y*2,width:sw*2,height:sh*2}).removeAlpha().resize(w,h,{fit:'fill'}).removeAlpha().raw().toBuffer();
 const original=sharp(a.buf,{raw:{width:sw,height:sh,channels:4}}).resize(w,h,{fit:'fill'});
 const alpha=await original.clone().extractChannel(3).raw().toBuffer();
 if(a.source.includes('/runtime-lvbu/')){
  // Keep the approved warm ink in the rider's shadows. The restoration model otherwise thickens them.
  const color=await original.removeAlpha().raw().toBuffer();
  for(let i=0;i<rgb.length;i+=3){
   const value=Math.max(rgb[i],rgb[i+1],rgb[i+2]),originalValue=Math.max(color[i],color[i+1],color[i+2]);
   if(value>=originalValue||value>=144)continue;
   const blend=Math.min(1,(144-value)/64);
   for(let ch=0;ch<3;ch++)rgb[i+ch]=Math.round(rgb[i+ch]*(1-blend)+color[i+ch]*blend);
  }
 }
 return sharp(rgb,{raw:{width:w,height:h,channels:3}}).joinChannel(alpha,{raw:{width:w,height:h,channels:1}}).png().toBuffer();
}
// Sort by height and find the smallest texture with shelf packing. Each patch owns a 2px gutter.
async function writeAtlas(dest,cells,layers){
 const order=cells.map((c,i)=>({i,w:c.content[2]+4,h:c.content[3]+4})).sort((a,b)=>b.h-a.h||b.w-a.w||a.i-b.i);
 const maxWidth=2048;let best;
 for(let width=Math.ceil(Math.max(...order.map(c=>c.w))/16)*16;width<=maxWidth;width+=16){
  const rows=[],rects=[];let height=0,used=0;
  for(const tile of order){
   let row=rows.find(r=>r.x+tile.w<=width);
   if(!row){row={x:0,y:height};rows.push(row);height+=tile.h;}
   rects[tile.i]=[row.x,row.y,tile.w,tile.h];row.x+=tile.w;used=Math.max(used,row.x);
  }
  const area=used*height;
  if(height<=2048&&(!best||area<best.area))best={width:used,height,area,rects};
 }
 if(!best)throw Error('Atlas exceeds 2048: '+dest);
 const images=layers.map((layer,i)=>{
  const cell=cells[i],[x,y]=best.rects[i];cell.packed=best.rects[i];
  return {input:layer.input,left:x+2,top:y+2};
 });
 await sharp({create:{width:best.width,height:best.height,channels:4,background:'#00000000'}})
  .composite(images).png({adaptiveFiltering:true,compressionLevel:9,palette:false}).toFile(dest);
 return best;
}
function writeLayout(atlases,file,exportName){
 const table={};
 for(const a of atlases){const name=a.dest.split('/').pop().slice(0,-4);
  table[name]=a.cells.map(c=>[...c.packed,c.rect[2],c.rect[3],c.content[0]-2,c.content[1]-2]);}
 fs.writeFileSync(file,'// Generated by the boss art packers. Packed rect, logical size, left/top trim.\nexport const '+exportName+' = '+JSON.stringify(table,null,0).replaceAll('],','],\n')+' as const;\n');
}
async function restoreFrame(atlas,index){
 const c=atlas.cells[index],[x,y,w,h]=c.packed,[,,ow,oh]=c.rect,left=c.content[0]-2,top=c.content[1]-2;
 return sharp(atlas.dest).extract({left:x,top:y,width:w,height:h})
  .extend({left,top,right:ow-left-w,bottom:oh-top-h,background:'#00000000'}).png().toBuffer();
}
module.exports={frameSize,sample,writeAtlas,writeLayout,restoreFrame};
